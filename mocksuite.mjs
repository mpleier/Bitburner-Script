async function runModule(file, ns, verbose) {
  const mod = await import(pathToFileURL(path.join(SCRIPTS, file)).href);
  if (typeof mod.main !== "function") {
    return ["library module: exports helpers only, no main()"];
  }
  await mod.main(ns);
  return ns.log;
}

