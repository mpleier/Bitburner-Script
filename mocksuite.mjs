/**
 * Authoritative RAM cost table.
 *
 * ramtable.json is generated by `node ramtable.mjs`, which evaluates the real
 * `RamCosts` tree from RamCostGenerator.ts, so the keys are full dotted paths
 * ("singularity.commitCrime" -> 5). ramcost.txt is only a leaf-name dump and is
 * kept as a fallback so the harness still works if ramtable.json is missing.
 */
function loadRamCost() {
  const map = new Map();
  const tablePath = path.join(process.cwd(), "ramtable.json");
  if (fs.existsSync(tablePath)) {
    for (const [name, cost] of Object.entries(JSON.parse(fs.readFileSync(tablePath, "utf8")))) {
      map.set(name, cost);
    }
    return map;
  }

  const raw = fs.readFileSync(path.join(process.cwd(), "ramcost.txt"));
  const txt = raw.slice(0, 2).toString("hex") === "fffe" ? raw.toString("utf16le") : raw.toString("utf8");
  for (const line of txt.split("\n")) {
    const m = line.trim().match(/^([a-zA-Z_][a-zA-Z0-9_]*)=([0-9.]+)$/);
    if (m) map.set(m[1], Number(m[2]));
  }
  return map;
}
const RAM_COST = loadRamCost();

/** Cost of `ns.<path>`, tolerating leaf-only tables. */
function ramCostOf(pathName) {
  if (RAM_COST.has(pathName)) return RAM_COST.get(pathName);
  const leaf = pathName.split(".").pop();
  return RAM_COST.get(leaf) ?? 0;
}



