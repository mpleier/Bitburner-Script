/** Mimics EnumHelper.nsGetMember: throw if the name is not an enum member. */
function assertEnum(fnName, argName, enumName, value) {
  const table = ENUMS[enumName];
  if (!table) return value; // mock does not model this enum, let it through
  const members = Object.values(table);
  if (members.includes(value)) return value;
  throw new Error(
    `${fnName}: Argument ${argName} should be a ${enumName} enum member.\nProvided value: "${value}".`
  );
}

/**
 * Authoritative RAM cost table.
 *
 * ramtable.json is generated by `node ramtable.mjs`, which evaluates the real
 * `RamCosts` tree from RamCostGenerator.ts, so the keys are full dotted paths
 * ("singularity.commitCrime" -> 5). It stores two scenarios:
 *   best  - SF4.3+ installed (Singularity API at base cost)
 *   worst - no SF4 at all    (SF4Cost multiplies Singularity API costs by 16)
 * ramcost.txt is only a leaf-name dump and is kept as a fallback.
 */
function loadRamCost() {
  const tablePath = path.join(process.cwd(), "ramtable.json");
  if (fs.existsSync(tablePath)) {
    const raw = JSON.parse(fs.readFileSync(tablePath, "utf8"));
    if (raw && raw.best && raw.worst) return raw;
    return { best: raw, worst: raw, namespaces: [] };
  }

  const raw = fs.readFileSync(path.join(process.cwd(), "ramcost.txt"));
  const txt = raw.slice(0, 2).toString("hex") === "fffe" ? raw.toString("utf16le") : raw.toString("utf8");
  const table = {};
  for (const line of txt.split("\n")) {
    const m = line.trim().match(/^([a-zA-Z_][a-zA-Z0-9_]*)=([0-9.]+)$/);
    if (m) table[m[1]] = Number(m[2]);
  }
  return { best: table, worst: table, namespaces: [] };
}
const RAM_COST = loadRamCost();

/**
 * Cost of `ns.<pathName>`, tolerating leaf-only tables and reproducing the
 * SF4Cost multiplier from RamCostGenerator.ts exactly.
 */
function ramCostOf(pathName, sf4Level = 4, bitNodeN = 8) {
  let base = RAM_COST.best[pathName];
  let worst = RAM_COST.worst[pathName];
  if (base === undefined) {
    const leaf = pathName.split(".").pop();
    base = RAM_COST.best[leaf];
    worst = RAM_COST.worst[leaf];
  }
  if (base === undefined) return 0;
  if (worst === base) return base;          // not SF4-gated
  if (bitNodeN === 4) return base;          // BN4: Singularity API is free-ish
  if (sf4Level <= 1) return base * 16;
  if (sf4Level === 2) return base * 4;
  return base;
}



